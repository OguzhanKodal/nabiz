const DICT: Record<Lang, Record<Key, string>> = { tr, en };

function detect(): Lang {
  try {
    const saved = localStorage.getItem("nabiz.lang");
    if (saved === "tr" || saved === "en") return saved;
  } catch {}
  return navigator.language?.toLowerCase().startsWith("tr") ? "tr" : "en";
}

export let lang: Lang = detect();

export function setLang(l: Lang) {
  lang = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem("nabiz.lang", l);
  } catch {}
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return DICT[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

// Arka uçtan gelen Türkçe hata metinlerini seçili dile çevirir.
const BACKEND_ERRORS: [string, Key][] = [
  ["Donanım bu değişikliği kabul etmedi", "err.rejected"],
  ["İzin verilmedi", "err.denied"],
  ["bu ayar bu cihazda yok", "err.missing"],
  ["RGB klavye bulunamadı", "err.noKbd"],
  ["güç modu desteklenmiyor", "err.noProfile"],
];

export function trError(e: unknown): string {
  const msg = String(e);
  const hit = BACKEND_ERRORS.find(([tr]) => msg.includes(tr));
  return hit ? t(hit[1]) : msg;
}

// Arka uç fan adlarını Türkçe verir.
export function fanLabel(label: string): string {
  if (label === "CPU fanı") return t("fan.cpu");
  if (label === "GPU fanı") return t("fan.gpu");
  return label;
}
